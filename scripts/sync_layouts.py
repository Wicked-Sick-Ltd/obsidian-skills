#!/usr/bin/env python3
"""Link passing Obsidian skills into each tool layout.

Canonical files live in plugins/obsidian/skills/<name>/. This script
symlinks that directory for Gemini CLI and symlinks each passing skill
into the Cursor, Claude Code, Codex, and Grok Bot directories. Skills
under held/ stay in the repo and are not linked.

    python3 scripts/sync_layouts.py        # write links and generated files
    python3 scripts/sync_layouts.py check  # fail if anything has drifted
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

PASSING = ("json-canvas", "obsidian-bases", "obsidian-markdown")
HELD = ("defuddle", "knap", "obsidian-cli", "obsidian-headless")
CANONICAL = Path("plugins/obsidian/skills")
GEMINI_LINK = Path("skills")
LAYOUTS = (
    Path(".cursor/skills"),
    Path(".claude/skills"),
    Path(".agents/skills"),
    Path(".grok/skills"),
)
PLUGIN_VERSION = Path("plugins/obsidian/plugin.json")


def repo_root_from_script() -> Path:
    return Path(__file__).resolve().parents[1]


BLOCK_SCALARS = {">", ">-", ">+", "|", "|-", "|+"}


def parse_scalar(value: str, path: Path, key: str) -> str:
    value = value.strip()
    if value in BLOCK_SCALARS:
        raise ValueError(f"{path} {key} uses a block scalar, which skill frontmatter does not support")
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
        return value[1:-1]
    return value


def read_frontmatter(text: str, path: Path) -> dict[str, str]:
    if not text.startswith("---\n"):
        raise ValueError(f"{path} is missing frontmatter")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise ValueError(f"{path} frontmatter is not closed")
    data: dict[str, str] = {}
    for line in text[4:end].splitlines():
        if not line.strip() or line.startswith(" ") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        key = key.strip()
        data[key] = parse_scalar(value, path, key)
    return data


def names_in(root: Path, relative: Path) -> list[str]:
    directory = root / relative
    if not directory.exists():
        return []
    return sorted(entry.name for entry in directory.iterdir())


def expected_skill_target(layout: Path, skill: str) -> str:
    return os.path.relpath(CANONICAL / skill, layout)


def gemini_description() -> str:
    return (
        "Obsidian Flavored Markdown, Bases, and JSON Canvas skills. "
        "Format guidance only."
    )


def render_gemini(version: str) -> str:
    payload = {
        "name": "obsidian-skills",
        "version": version,
        "description": gemini_description(),
    }
    return json.dumps(payload, indent=2) + "\n"


def render_agents(root: Path) -> str:
    lines = [
        "<!-- Generated by scripts/sync_layouts.py. Edit skills under plugins/obsidian/skills/, then re-run the script. -->",
        "",
        "# Obsidian skills",
        "",
        "Codex loads `.agents/skills/`. Each entry is a symlink to the canonical skill in `plugins/obsidian/skills/`. Gemini CLI loads the `skills/` symlink, which points at that same directory. Only skills that passed review are linked. Skills under `held/` are not loaded.",
        "",
        "| Skill | Description |",
        "| --- | --- |",
    ]
    for skill in PASSING:
        path = root / CANONICAL / skill / "SKILL.md"
        meta = read_frontmatter(path.read_text(encoding="utf-8"), path)
        description = meta.get("description", "")
        if not description:
            raise ValueError(f"{path} description is empty")
        lines.append(f"| `{skill}` | {description} |")
    lines.append("")
    return "\n".join(lines)


def plugin_version(root: Path) -> str:
    payload = json.loads((root / PLUGIN_VERSION).read_text(encoding="utf-8"))
    version = payload.get("version")
    if not isinstance(version, str) or not version:
        raise ValueError(f"{PLUGIN_VERSION} has no version")
    return version


def ensure_symlink(link: Path, target: str) -> None:
    if link.is_symlink():
        if os.readlink(link) == target:
            return
        link.unlink()
    elif link.exists():
        raise SystemExit(f"{link} exists and is not a symlink; refusing to replace it")
    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(target)


def remove_obsolete_links(root: Path) -> None:
    """Drop leftover symlinks. A real extra file is left alone and fails check."""
    for layout in LAYOUTS:
        directory = root / layout
        if not directory.is_dir():
            continue
        for entry in list(directory.iterdir()):
            if entry.name in PASSING:
                continue
            if entry.is_symlink():
                entry.unlink()


def sync(root: Path) -> None:
    errors = validate(root, layouts_ready=False)
    structural = [item for item in errors if not item.startswith("layout:") and not item.startswith("generated:")]
    if structural:
        raise SystemExit("\n".join(structural))
    ensure_symlink(root / GEMINI_LINK, CANONICAL.as_posix())
    for layout in LAYOUTS:
        directory = root / layout
        directory.mkdir(parents=True, exist_ok=True)
        for skill in PASSING:
            ensure_symlink(directory / skill, expected_skill_target(layout, skill))
    remove_obsolete_links(root)
    version = plugin_version(root)
    (root / "gemini-extension.json").write_text(render_gemini(version), encoding="utf-8")
    (root / "AGENTS.md").write_text(render_agents(root), encoding="utf-8")
    drifted = check(root)
    if drifted:
        raise SystemExit("\n".join(drifted))


def validate(root: Path, layouts_ready: bool = True) -> list[str]:
    errors: list[str] = []
    canonical = root / CANONICAL
    if not canonical.is_dir() or canonical.is_symlink():
        errors.append(f"canonical: {CANONICAL} must be a real directory")
        return errors

    found = names_in(root, CANONICAL)
    if tuple(found) != PASSING:
        errors.append(f"canonical: expected {list(PASSING)}, found {found}")

    held = root / "held"
    if not held.is_dir() or held.is_symlink():
        errors.append("held: held/ must be a real directory")
    else:
        found_held = names_in(root, Path("held"))
        if tuple(found_held) != HELD:
            errors.append(f"held: expected {list(HELD)}, found {found_held}")

    for skill in PASSING:
        skill_dir = canonical / skill
        if skill_dir.is_symlink() or not skill_dir.is_dir():
            errors.append(f"canonical: {skill} must be a real directory")
            continue
        skill_file = skill_dir / "SKILL.md"
        if not skill_file.is_file():
            errors.append(f"canonical: {skill} has no SKILL.md")
            continue
        try:
            meta = read_frontmatter(skill_file.read_text(encoding="utf-8"), skill_file)
        except ValueError as exc:
            errors.append(str(exc))
            continue
        if meta.get("name") != skill:
            errors.append(f"canonical: {skill} frontmatter name is {meta.get('name')!r}")
        if not meta.get("description"):
            errors.append(f"canonical: {skill} description is empty")

    for skill in HELD:
        if (canonical / skill).exists():
            errors.append(f"canonical: held skill {skill} is still in {CANONICAL}")

    if not layouts_ready:
        return errors

    gemini = root / GEMINI_LINK
    if not gemini.is_symlink():
        errors.append("layout: skills must be a symlink to plugins/obsidian/skills")
    elif os.readlink(gemini) != CANONICAL.as_posix():
        errors.append(f"layout: skills points at {os.readlink(gemini)!r}")

    for layout in LAYOUTS:
        directory = root / layout
        if not directory.is_dir():
            errors.append(f"layout: missing {layout}")
            continue
        found_layout = names_in(root, layout)
        if tuple(found_layout) != PASSING:
            errors.append(f"layout: {layout} expected {list(PASSING)}, found {found_layout}")
        for skill in PASSING:
            link = directory / skill
            target = expected_skill_target(layout, skill)
            if not link.is_symlink():
                errors.append(f"layout: {layout / skill} is not a symlink")
                continue
            actual = os.readlink(link)
            if actual != target:
                errors.append(f"layout: {layout / skill} points at {actual!r}, expected {target!r}")
            elif not (root / layout / skill / "SKILL.md").is_file():
                errors.append(f"layout: {layout / skill} does not resolve to SKILL.md")
        for skill in HELD:
            if (directory / skill).exists():
                errors.append(f"layout: held skill {skill} is linked from {layout}")

    try:
        version = plugin_version(root)
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        errors.append(f"generated: {exc}")
        version = ""
    gemini_file = root / "gemini-extension.json"
    agents_file = root / "AGENTS.md"
    if version:
        expected_gemini = render_gemini(version)
        actual_gemini = gemini_file.read_text(encoding="utf-8") if gemini_file.is_file() else ""
        if actual_gemini != expected_gemini:
            errors.append("generated: gemini-extension.json has drifted")
        if any(skill in actual_gemini for skill in HELD):
            errors.append("generated: gemini-extension.json names a held skill")
    expected_agents = ""
    try:
        expected_agents = render_agents(root)
    except (OSError, ValueError) as exc:
        errors.append(f"generated: AGENTS.md could not be rendered ({exc})")
    actual_agents = agents_file.read_text(encoding="utf-8") if agents_file.is_file() else ""
    if expected_agents and actual_agents != expected_agents:
        errors.append("generated: AGENTS.md has drifted")
    for skill in HELD:
        if skill in actual_agents:
            errors.append(f"generated: AGENTS.md names held skill {skill}")
    return errors


def check(root: Path) -> list[str]:
    return validate(root, layouts_ready=True)


def main(argv: list[str]) -> int:
    command = argv[1] if len(argv) > 1 else "sync"
    root = Path(argv[2]).resolve() if len(argv) > 2 else repo_root_from_script()
    if command == "sync":
        sync(root)
        return 0
    if command == "check":
        errors = check(root)
        if errors:
            print("\n".join(errors), file=sys.stderr)
            return 1
        print(f"layouts match {len(PASSING)} passing skills")
        return 0
    print("usage: sync_layouts.py [sync|check] [root]", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
